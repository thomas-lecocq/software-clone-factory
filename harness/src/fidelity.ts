/**
 * The fidelity report: one page per target that says what a clone is worth, in the same nine
 * sections for every target, so that two clones can be compared and a buyer can check each claim.
 * Five sections are computed from the run (clean measurement, bound, coverage, determinism,
 * integrity), two are declared by hand in GAPS.md (scope, divergences), one comes from the agent
 * logs (saturation) and one says plainly when it does not apply (task validation). Holdout
 * results appear as totals only, so the report is safe to show an implementer.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import type { RuleResult } from "./ledger.ts";

export interface Tally {
  pass: number;
  total: number;
}

export interface FidelityInput {
  target: string;
  at: string;
  dev: Tally;
  // Pre-registered batches (IDs starting with `hold-`) and the hash-split holdout, apart.
  batch: Tally;
  hashHoldout: Tally;
  pixelsReported: number;
  statuses: RuleResult[];
  holdoutRules: Set<string>;
  determinism: { identical: number; total: number };
  integrity: {
    lockIntact: boolean;
    lockHash: string;
    commit: string | null;
    dirty: boolean | null;
    sandbox: boolean;
    holdoutLooks: number;
  };
  gaps: string | null;
  breakerLogs: string[];
  // Commits that changed the diff policy after the analysis plan was committed.
  policySincePlan: string[] | null;
}

// One-sided exact (Clopper-Pearson) upper bound on the failure rate, given k failures in n.
export function upperBound(k: number, n: number, alpha = 0.05): number {
  if (n === 0) return 1;
  if (k >= n) return 1;
  const cdf = (p: number): number => {
    let term = (1 - p) ** n;
    let sum = term;
    for (let i = 1; i <= k; i += 1) {
      term *= ((n - i + 1) / i) * (p / (1 - p));
      sum += term;
    }
    return sum;
  };
  let lo = 0;
  let hi = 1;
  for (let i = 0; i < 60; i += 1) {
    const mid = (lo + hi) / 2;
    if (cdf(mid) > alpha) lo = mid;
    else hi = mid;
  }
  return hi;
}

const pct = (x: number): string => `${(x * 100).toFixed(2)} %`;

function measured(name: string, t: Tally): string {
  if (t.total === 0) return `| ${name} | none | | | |`;
  const k = t.total - t.pass;
  const b95 = pct(upperBound(k, t.total));
  const b99 = pct(upperBound(k, t.total, 0.01));
  return `| ${name} | ${String(t.pass)} of ${String(t.total)} | ${String(k)} | ${b95} | ${b99} |`;
}

// A `## <title>` section of GAPS.md, without its heading.
export function section(markdown: string | null, title: string): string | null {
  if (markdown === null) return null;
  const lines = markdown.split("\n");
  const start = lines.findIndex((l) => l.trim().toLowerCase() === `## ${title}`.toLowerCase());
  if (start < 0) return null;
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((l) => l.startsWith("## "));
  return (end < 0 ? rest : rest.slice(0, end)).join("\n").trim();
}

export function fidelityReport(f: FidelityInput): string {
  const verified = f.statuses.filter((s) => s.status === "verified");
  const withHoldout = verified.filter((s) => f.holdoutRules.has(s.rule.id));
  const failing = f.statuses.filter((s) => s.status === "failing");
  const unverified = f.statuses.filter((s) => s.status === "unverified");
  const i = f.integrity;
  return [
    `# Fidelity report: ${f.target}`,
    "",
    `Generated by \`npm run verify\` on ${f.at}. Do not edit: sections 1 and 6 come from`,
    "`GAPS.md`, the others from the run, the rule ledger and the agent logs.",
    "",
    "## 1. Scope",
    "",
    section(f.gaps, "Scope") ?? "Not declared: add a `## Scope` section to `GAPS.md`.",
    "",
    "## 2. Clean measurement",
    "",
    "Fixtures recorded from the real target, replayed against a freshly reset clone. Only holdout",
    "cases the builder never saw count as clean; dev cases are training data.",
    "",
    "| Set | Passing | Failures | Upper bound on the failure rate, 95 % | Same, 99 % |",
    "| --- | --- | --- | --- | --- |",
    measured("Pre-registered holdout batch", f.batch),
    measured("Hash-split holdout", f.hashHoldout),
    measured("Dev (training, not a claim)", f.dev),
    "",
    `Perceptual pixel differences reported, never scored: ${String(f.pixelsReported)}.`,
    "",
    "## 3. Bound",
    "",
    "One-sided exact (Clopper-Pearson) bounds at 95 % and 99 %, valid for the distribution each set was",
    "drawn from and for nothing outside it. A pre-registered batch has its plan in",
    "`analysis-plan.md`; with no failure in n cases the 95 % bound is 1 − 0.05^(1/n).",
    "",
    f.policySincePlan === null
      ? "No analysis plan committed."
      : f.policySincePlan.length === 0
        ? "Diff policy unchanged since the analysis plan was committed."
        : `Diff policy changed since the analysis plan was committed: ${f.policySincePlan.join("; ")}.`,
    "",
    "## 4. Coverage",
    "",
    `- Rules in the ledger: ${String(f.statuses.length)}.`,
    `- Verified on dev: ${String(verified.length)}, of which ${String(withHoldout.length)} also have holdout fixtures.`,
    `- Failing on dev: ${failing.length === 0 ? "none" : failing.map((s) => s.rule.id).join(", ")}.`,
    `- Unverified (no fixture): ${unverified.length === 0 ? "none" : unverified.map((s) => s.rule.id).join(", ")}.`,
    "- Per rule and split: `coverage.md`.",
    "",
    "## 5. Determinism",
    "",
    `${String(f.determinism.identical)} of ${String(f.determinism.total)} sampled fixtures gave identical`,
    "output on two runs, each after `POST /__reset` (generated IDs canonicalised).",
    "",
    "## 6. Divergences",
    "",
    section(f.gaps, "Measured divergences") ?? "Not declared in `GAPS.md`.",
    "",
    "Thin rules, blind spots and behaviour compared nowhere: `GAPS.md`.",
    "",
    "## 7. Saturation",
    "",
    f.breakerLogs.length === 0
      ? "No breaker round logged: nobody has tried to find inputs where the clone diverges."
      : `${String(f.breakerLogs.length)} breaker round(s) logged: ${f.breakerLogs.join(", ")}.`,
    "",
    "## 8. Task validation",
    "",
    "Not applicable: no downstream task suite exists for this target, so whether agents trained on",
    "the clone succeed on the original was never measured.",
    "",
    "## 9. Integrity",
    "",
    `- Evaluator lock: ${i.lockIntact ? "intact" : "BROKEN"} (\`${i.lockHash}\`).`,
    `- Commit: ${i.commit ?? "none (outside git)"}${i.dirty === true ? ", with uncommitted changes to the harness or targets" : ""}.`,
    `- Run inside a builder sandbox: ${i.sandbox ? "yes (the holdout is absent there)" : "no"}.`,
    `- Scored runs that looked at the holdout under this lock, this one included: ${String(i.holdoutLooks)}. A`,
    "  holdout that drove a decision is spent; see `analysis-plan.md` for the batch's single look.",
    "",
  ].join("\n");
}

const RunLine = z.object({
  lock: z.string(),
  holdout: z.object({ total: z.number() }),
});

export function holdoutLooks(runsFile: string, lock: string): number {
  if (!existsSync(runsFile)) return 0;
  return readFileSync(runsFile, "utf8")
    .split("\n")
    .filter((l) => l.trim() !== "")
    .map((l) => RunLine.safeParse(JSON.parse(l)))
    .filter((r) => r.success && r.data.lock === lock && r.data.holdout.total > 0).length;
}

export function breakerLogs(dir: string): string[] {
  const logs = join(dir, "logs");
  if (!existsSync(logs)) return [];
  return readdirSync(logs)
    .filter((f) => f.startsWith("breaker-"))
    .sort();
}
