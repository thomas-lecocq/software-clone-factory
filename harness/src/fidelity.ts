/**
 * The fidelity report: one page per target that says what a clone is worth, in the same nine
 * sections for every target, so that two clones can be compared and a buyer can check each claim.
 * Five sections are computed from the run (clean measurement, bound, coverage, determinism,
 * integrity), two are declared by hand in GAPS.md (scope, divergences), one comes from the agent
 * logs (saturation) and one says plainly when it does not apply (task validation). Holdout
 * results appear as totals only, so the report is safe to show an implementer.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { z } from "zod";
import type { RuleResult } from "./ledger.ts";

export interface Tally {
  pass: number;
  total: number;
}

export interface BatchPlan {
  file: string;
  // Commits that changed the diff policy after the plan; null when history cannot tell.
  policyChanges: string[] | null;
  // Whether git shows the plan committed strictly before the batch's first fixture.
  preRegistered: "yes" | "no" | "cannot check";
}

export interface FidelityInput {
  target: string;
  at: string;
  dev: Tally;
  // Pre-registered batches (IDs `hold-…-NNN`, keyed by prefix) and the hash-split holdout, apart.
  batches: Record<string, Tally>;
  hashHoldout: Tally;
  pixelsReported: number;
  statuses: RuleResult[];
  holdoutRules: Set<string>;
  determinism: { identical: number; total: number };
  integrity: {
    lockIntact: boolean;
    lockHash: string;
    commit: string | null;
    dirty: boolean | null;
    sandbox: boolean;
  };
  // Scored runs that included each holdout set ("hash" or a batch prefix), this one included.
  looks: Record<string, number>;
  // Per batch prefix: its plan file and the commits that changed the diff policy since it.
  plans: Record<string, BatchPlan>;
  gaps: string | null;
  // Breaker rounds stored as data (`breaker-round*.json`), so they survive a fresh clone.
  breakerRounds: string[];
}

// One-sided exact (Clopper-Pearson) upper bound on the failure rate, given k failures in n.
export function upperBound(k: number, n: number, alpha = 0.05): number {
  if (n === 0) return 1;
  if (k >= n) return 1;
  const cdf = (p: number): number => {
    let term = (1 - p) ** n;
    let sum = term;
    for (let i = 1; i <= k; i += 1) {
      term *= ((n - i + 1) / i) * (p / (1 - p));
      sum += term;
    }
    return sum;
  };
  let lo = 0;
  let hi = 1;
  for (let i = 0; i < 60; i += 1) {
    const mid = (lo + hi) / 2;
    if (cdf(mid) > alpha) lo = mid;
    else hi = mid;
  }
  return hi;
}

const pct = (x: number): string => `${(x * 100).toFixed(2)} %`;

function measured(name: string, t: Tally, status: string): string {
  if (t.total === 0) return `| ${name} | none | | | | ${status} |`;
  const k = t.total - t.pass;
  const b95 = pct(upperBound(k, t.total));
  const b99 = pct(upperBound(k, t.total, 0.01));
  return `| ${name} | ${String(t.pass)} of ${String(t.total)} | ${String(k)} | ${b95} | ${b99} | ${status} |`;
}

// Only a pre-registered batch on its single look carries a claim; every other set is reported
// with the reason it cannot.
function batchStatus(looks: number, plan: BatchPlan | undefined): string {
  if (plan === undefined) return `no plan found; ${String(looks)} look(s), no claim`;
  if (plan.preRegistered === "no")
    return `plan \`${plan.file}\` committed after the batch: no claim`;
  const order =
    plan.preRegistered === "yes" ? "plan committed first" : "plan order cannot be checked here";
  if (looks <= 1) return `first and only look; \`${plan.file}\`, ${order}`;
  return `spent: ${String(looks)} looks; its claim rests on the first (\`measurements.md\`); ${order}`;
}

// A `## <title>` section of GAPS.md, without its heading.
export function section(markdown: string | null, title: string): string | null {
  if (markdown === null) return null;
  const lines = markdown.split("\n");
  const start = lines.findIndex((l) => l.trim().toLowerCase() === `## ${title}`.toLowerCase());
  if (start < 0) return null;
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((l) => l.startsWith("## "));
  return (end < 0 ? rest : rest.slice(0, end)).join("\n").trim();
}

// `hold-042` belongs to batch `hold`, `hold-b2-042` to batch `hold-b2`.
export const batchOf = (id: string): string => id.replace(/-\d+$/, "");

export function fidelityReport(f: FidelityInput): string {
  const verified = f.statuses.filter((s) => s.status === "verified");
  const withHoldout = verified.filter((s) => f.holdoutRules.has(s.rule.id));
  const failing = f.statuses.filter((s) => s.status === "failing");
  const unverified = f.statuses.filter((s) => s.status === "unverified");
  const i = f.integrity;
  return [
    `# Fidelity report: ${f.target}`,
    "",
    `Generated by \`npm run verify\` on ${f.at}. Do not edit: sections 1 and 6 come from`,
    "`GAPS.md`, the others from the run, the rule ledger and the agent logs.",
    "",
    "## 1. Scope",
    "",
    section(f.gaps, "Scope") ?? "Not declared: add a `## Scope` section to `GAPS.md`.",
    "",
    "## 2. Clean measurement",
    "",
    "Fixtures recorded from the real target, replayed against a freshly reset clone. Only holdout",
    "cases the builder never saw count as clean; dev cases are training data.",
    "",
    "| Set | Passing | Failures | Upper bound on the failure rate, 95 % | Same, 99 % | Status |",
    "| --- | --- | --- | --- | --- | --- |",
    ...Object.entries(f.batches)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([prefix, t]) =>
        measured(
          `Pre-registered batch \`${prefix}-\``,
          t,
          batchStatus(f.looks[prefix] ?? 1, f.plans[prefix]),
        ),
      ),
    measured(
      "Hash-split holdout",
      f.hashHoldout,
      `looked at ${String(f.looks.hash ?? 1)} time(s) and holds cases designed after earlier failures: no claim`,
    ),
    measured("Dev", f.dev, "training data, no claim"),
    "",
    `Perceptual pixel differences reported, never scored: ${String(f.pixelsReported)}.`,
    "",
    "## 3. Bound",
    "",
    "One-sided exact (Clopper-Pearson) bounds at 95 % and 99 %, valid for the distribution each set",
    "was drawn from and for nothing outside it. A claim rests only on a pre-registered batch's first",
    "look, recorded in `measurements.md`. With no failure in n cases the 95 % bound is 1 − 0.05^(1/n).",
    "",
    ...Object.entries(f.plans)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([prefix, p]) =>
        p.policyChanges === null
          ? `- Batch \`${prefix}-\`: whether the diff policy changed since \`${p.file}\` cannot be checked from this history.`
          : p.policyChanges.length === 0
            ? `- Batch \`${prefix}-\`: diff policy unchanged since \`${p.file}\` was committed.`
            : `- Batch \`${prefix}-\`: diff policy changed since \`${p.file}\` was committed: ${p.policyChanges.join("; ")}.`,
      ),
    "",
    "## 4. Coverage",
    "",
    `- Rules in the ledger: ${String(f.statuses.length)}.`,
    `- Verified on dev: ${String(verified.length)}, of which ${String(withHoldout.length)} also have holdout fixtures.`,
    `- Failing on dev: ${failing.length === 0 ? "none" : failing.map((s) => s.rule.id).join(", ")}.`,
    `- Unverified (no fixture): ${unverified.length === 0 ? "none" : unverified.map((s) => s.rule.id).join(", ")}.`,
    "- Per rule and split: `coverage.md`.",
    "",
    "## 5. Determinism",
    "",
    `${String(f.determinism.identical)} of ${String(f.determinism.total)} sampled fixtures gave identical`,
    "output on two runs, each after `POST /__reset` (generated IDs canonicalised).",
    "",
    "## 6. Divergences",
    "",
    section(f.gaps, "Measured divergences") ?? "Not declared in `GAPS.md`.",
    "",
    "Thin rules, blind spots and behaviour compared nowhere: `GAPS.md`.",
    "",
    "## 7. Saturation",
    "",
    f.breakerRounds.length === 0
      ? "No breaker round stored: nobody has tried to find inputs where the clone diverges."
      : `${String(f.breakerRounds.length)} breaker round(s) stored (${f.breakerRounds.join(", ")}); their probes are dev cases, scored with the rest. A round that finds nothing new would mark saturation.`,
    "",
    "## 8. Task validation",
    "",
    "Not applicable: no downstream task suite exists for this target, so whether agents trained on",
    "the clone succeed on the original was never measured.",
    "",
    "## 9. Integrity",
    "",
    `- Evaluator lock: ${i.lockIntact ? "intact" : "BROKEN"} (\`${i.lockHash}\`).`,
    `- Commit: ${i.commit ?? "none (outside git)"}${i.dirty === true ? ", with uncommitted changes to the harness or targets" : ""}.`,
    `- Run inside a builder sandbox: ${i.sandbox ? "yes (the holdout is absent there)" : "no"}.`,
    `- Looks per holdout set, every lock included: ${
      Object.entries(f.looks)
        .map(([k, n]) => `${k} ${String(n)}`)
        .join(", ") || "none"
    }. Runs logged before sets were recorded count for every set.`,
    "",
  ].join("\n");
}

const RunLine = z.object({
  holdout: z.object({ total: z.number() }),
  sets: z.array(z.string()).optional(),
});

// Counted over every run of the log, whatever its lock: a relock does not make a holdout fresh.
export function looksPerSet(runsFile: string, sets: string[]): Record<string, number> {
  const looks = Object.fromEntries(sets.map((s) => [s, 0]));
  if (!existsSync(runsFile)) return looks;
  for (const line of readFileSync(runsFile, "utf8").split("\n")) {
    if (line.trim() === "") continue;
    const r = RunLine.safeParse(JSON.parse(line));
    if (!r.success || r.data.holdout.total === 0) continue;
    for (const s of r.data.sets ?? sets) if (s in looks) looks[s] = (looks[s] ?? 0) + 1;
  }
  return looks;
}

export function breakerRounds(dir: string): string[] {
  return readdirSync(dir)
    .filter((f) => /^breaker-round.*\.json$/.test(f))
    .sort();
}
